const CODE_SET: ReadonlySet<string> = new Set(COUNTRY_CODES);

export const DEFAULT_COUNTRY = 'BE';

export function isCountryCode(value: string): boolean {
  return CODE_SET.has(value);
}

// Nom du pays en francais ; le code lui-meme si Intl ne le connait pas.
export function countryName(code: string): string {
  try {
    return new Intl.DisplayNames(['fr'], { type: 'region' }).of(code) ?? code;
  } catch {
    return code;
  }
}

export type CountryOption = { code: string; name: string };

// Pays voisins d'abord (clientele d'un cabinet belge), puis tous les autres
// par ordre alphabetique francais.
const PRIORITY = ['BE', 'FR', 'LU', 'NL', 'DE'];

export function countryOptions(): CountryOption[] {
  const collator = new Intl.Collator('fr');
  const all = COUNTRY_CODES.map((code) => ({ code, name: countryName(code) }));
  const head = PRIORITY.map((code) => all.find((c) => c.code === code)!);
  const rest = all
    .filter((c) => !PRIORITY.includes(c.code))
    .sort((a, b) => collator.compare(a.name, b.name));
  return [...head, ...rest];
}
